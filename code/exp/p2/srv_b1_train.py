"""Y1 (paper 2): train two LoRAs from scratch, so kappa stops resting on one
checkpoint.

The soft spot this closes: te_only / unet_only / no_attn2 / r4 are all weight
surgery on a *single* file, `lora_detail_sd15.safetensors`.  A reviewer needs
one sentence -- "what if you trained your own?" -- to invalidate every
cross-configuration claim.  ModelScope has exactly one SD1.5 LoRA and its
byte count is identical to the local one, so there is nothing to download; the
only way out is to train.

Design
  * two *different* concepts, different seeds, trained in separate runs.  A is
    a flat-vector look (thick outlines, teal/coral), B is an ink-wash look
    (monochrome grey, soft strokes).  Different enough that a shared kappa
    cannot be an artefact of "both are the same style".
  * the concept set is generated by the base model itself (24 images per
    concept, fixed seeds) so there is no download, no licence question, and the
    set is reproducible from this file alone.  The LoRA then learns a style the
    base model can already produce -- which is exactly what a style LoRA is.
  * rank 8, alpha 8.  TARA (AAAI'26) trains SD1.5 LoRA at rank 8, so the
    configuration sits in the published band rather than at an extreme, and
    E2c-2's rank-4 arm already covers the low end.
  * 800 steps, lr 1e-4, cosine with 50-step warmup, batch 1, 512 px.  Small on
    purpose: the goal is a *usable* w axis, not a pretty LoRA.
  * fp32 UNet + gradient checkpointing.  An 8 GB laptop card cannot hold an
    fp16 UNet plus autocast state plus Adam without spilling; fp32 UNet with
    only the 0.5 M LoRA parameters trainable fits with ~2 GB to spare.

What would mean failure
  * the verification step generates the same prompt at w=0 and w=2 and measures
    the image distance.  If it is below ~2 (the scale pix_l2_base runs at when
    a LoRA is doing something, cf. L2's 3-9 range) the LoRA is inert, kappa
    would be unmeasurable for exactly the same reason te_only was, and the run
    has to be reported as "untrained" rather than "no collinearity".

Run:
    python y1_train.py --concept A --steps 800
    python y1_train.py --concept A --steps 4 --smoke
"""
from __future__ import annotations

import argparse
import json
import math
import os
import time

import numpy as np
import torch
import torch.nn.functional as F

HERE = os.path.dirname(os.path.abspath(__file__))
SD15 = "/home/wang_jianhao/models/v1-5-pruned-emaonly.safetensors"
CFG = None
CONCEPT_ROOT = "/home/wang_jianhao/b1/concepts"
LORA_OUT = "/home/wang_jianhao/b1/lora"

SUBJECTS = ["a teapot", "a wooden chair", "a bicycle", "a lighthouse",
            "a coffee cup", "a mountain range", "a sailing boat", "a mushroom",
            "a hot air balloon", "a street lamp", "a rose", "a small house"]

CONCEPTS = {
    "A": dict(
        style=("flat vector illustration, thick black outlines, limited palette "
               "of teal and coral, simple geometric shapes, plain background"),
        seeds=[101, 202]),
    "B": dict(
        style=("traditional chinese ink wash painting, monochrome grey, soft wet "
               "brush strokes, misty paper texture, lots of negative space"),
        seeds=[303, 404]),
    # C added 2026-11-10 for the multi-LoRA probe (execution plan §3.1).  Hard-edged
    # graphite against B's soft monochrome and A's flat colour, so the three adapters
    # differ in both palette and stroke physics.  A and B are untouched on purpose:
    # every Y-series number was measured on them.
    "C": dict(
        style=("graphite pencil sketch, hard cross-hatched shading, visible paper "
               "grain, high contrast black and white, no colour"),
        seeds=[505, 606]),
}


def concept_dir(c):
    return os.path.join(CONCEPT_ROOT, c)


def build_concept(c, steps_img=20):
    """24 (image, caption) pairs generated by the base model, cached on disk."""
    d = concept_dir(c)
    meta = os.path.join(d, "captions.json")
    if os.path.exists(meta):
        return json.load(open(meta))
    os.makedirs(d, exist_ok=True)

    from diffusers import DDIMScheduler, StableDiffusionPipeline
    pipe = StableDiffusionPipeline.from_single_file(
        SD15, torch_dtype=torch.float16,
        use_safetensors=True, local_files_only=True)
    pipe.scheduler = DDIMScheduler.from_config(pipe.scheduler.config)
    pipe.set_progress_bar_config(disable=True)
    pipe = pipe.to("cuda")

    style = CONCEPTS[c]["style"]
    items, i = [], 0
    for sd in CONCEPTS[c]["seeds"]:
        for subj in SUBJECTS:
            cap = f"{style}, {subj}"
            g = torch.Generator(device="cpu").manual_seed(sd + i)
            img = pipe(prompt=cap, num_inference_steps=steps_img, guidance_scale=7.5,
                       generator=g, height=512, width=512,
                       return_dict=False)[0][0]
            p = os.path.join(d, f"{i:02d}.png")
            img.save(p)
            items.append(dict(path=p, caption=cap))
            i += 1
    json.dump(items, open(meta, "w"), indent=1)
    del pipe
    torch.cuda.empty_cache()
    print(f"  built {len(items)} concept images for {c} -> {d}", flush=True)
    return items


def precompute(items):
    """(latents, embeds) -- so the training loop never touches VAE or CLIP."""
    from diffusers import StableDiffusionPipeline
    from PIL import Image
    pipe = StableDiffusionPipeline.from_single_file(
        SD15, torch_dtype=torch.float32,
        use_safetensors=True, local_files_only=True)
    pipe.set_progress_bar_config(disable=True)
    vae, te, tok = pipe.vae.to("cuda").eval(), pipe.text_encoder, pipe.tokenizer
    te = te.to("cuda").eval()

    lat, emb = [], []
    with torch.no_grad():
        for it in items:
            im = Image.open(it["path"]).convert("RGB").resize((512, 512))
            x = torch.from_numpy(np.asarray(im, np.float32) / 127.5 - 1.0)
            x = x.permute(2, 0, 1)[None].to("cuda", torch.float32)
            lat.append(vae.encode(x).latent_dist.sample() * 0.18215)
            t = tok(it["caption"], padding="max_length", max_length=77,
                    truncation=True, return_tensors="pt").to("cuda")
            emb.append(te(**t).last_hidden_state)
    lat = torch.cat(lat).cpu()
    emb = torch.cat(emb).cpu()
    del vae, te, pipe
    torch.cuda.empty_cache()
    return lat, emb


def train(lat, emb, steps, rank, lr, out_path, warmup=50, log_every=25):
    from diffusers import DDPMScheduler, StableDiffusionPipeline
    from peft import LoraConfig, get_peft_model_state_dict
    from diffusers.utils import convert_state_dict_to_diffusers
    from diffusers.loaders import StableDiffusionLoraLoaderMixin

    pipe = StableDiffusionPipeline.from_single_file(
        SD15, torch_dtype=torch.float32,
        use_safetensors=True, local_files_only=True)
    pipe.set_progress_bar_config(disable=True)
    unet = pipe.unet.to("cuda").train()
    unet.requires_grad_(False)
    unet.add_adapter(LoraConfig(
        r=rank, lora_alpha=rank, init_lora_weights="gaussian",
        target_modules=["to_q", "to_k", "to_v", "to_out.0"]))
    unet.enable_gradient_checkpointing()
    params = [p for p in unet.parameters() if p.requires_grad]
    n_par = sum(p.numel() for p in params)
    opt = torch.optim.AdamW(params, lr=lr, weight_decay=1e-2, betas=(0.9, 0.999))
    sched = DDPMScheduler.from_config(pipe.scheduler.config)
    n_img = lat.shape[0]
    print(f"  trainable params {n_par/1e6:.2f} M over {n_img} images, "
          f"{steps} steps, rank {rank}", flush=True)

    rng = np.random.default_rng(0)
    t0, losses = time.time(), []
    for st in range(1, steps + 1):
        cur_lr = lr * (st / warmup if st < warmup else
                       0.5 * (1 + math.cos(math.pi * (st - warmup) /
                                           max(1, steps - warmup))))
        for g in opt.param_groups:
            g["lr"] = cur_lr
        i = int(rng.integers(n_img))
        x0 = lat[i:i + 1].to("cuda")
        e = emb[i:i + 1].to("cuda")
        noise = torch.randn_like(x0)
        tt = torch.randint(0, sched.config.num_train_timesteps, (1,),
                           device="cuda").long()
        xn = sched.add_noise(x0, noise, tt)
        pred = unet(xn, tt, encoder_hidden_states=e).sample
        loss = F.mse_loss(pred.float(), noise.float())
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(params, 1.0)
        opt.step()
        losses.append(float(loss.detach()))
        if st % log_every == 0 or st == 1:
            el = time.time() - t0
            print(f"    step {st:4d}/{steps}  loss {np.mean(losses[-log_every:]):.4f}"
                  f"  lr {cur_lr:.2e}  {el/st*1000:.0f} ms/step  "
                  f"eta {(steps-st)*el/st/60:.1f} min", flush=True)

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    sd = convert_state_dict_to_diffusers(get_peft_model_state_dict(unet))
    d = out_path.replace(".safetensors", "")
    os.makedirs(d, exist_ok=True)
    StableDiffusionLoraLoaderMixin.save_lora_weights(
        save_directory=d, unet_lora_layers=sd, safe_serialization=True)
    made = os.path.join(d, "pytorch_lora_weights.safetensors")
    if os.path.exists(made) and made != out_path:
        os.replace(made, out_path)
    print(f"  saved {out_path}  ({os.path.getsize(out_path)/1e6:.2f} MB, "
          f"{len(sd)} tensors)", flush=True)
    del unet, pipe
    torch.cuda.empty_cache()
    return float(np.mean(losses[-50:]))


def verify(lora_path, prompts, seeds=(11,)):
    """Does the LoRA actually move the picture?  w=0 vs w=2, pix_l2_base scale."""
    from diffusers import DDIMScheduler, StableDiffusionPipeline
    pipe = StableDiffusionPipeline.from_single_file(
        SD15, torch_dtype=torch.float16,
        use_safetensors=True, local_files_only=True)
    pipe.scheduler = DDIMScheduler.from_config(pipe.scheduler.config)
    pipe.set_progress_bar_config(disable=True)
    pipe = pipe.to("cuda")
    pipe.load_lora_weights(lora_path, adapter_name="v")

    def gen(p, w, sd):
        pipe.set_adapters(["v"], [float(w)])
        g = torch.Generator(device="cpu").manual_seed(int(sd))
        im = pipe(prompt=p, num_inference_steps=20, guidance_scale=7.5,
                  generator=g, height=512, width=512, return_dict=False)[0][0]
        return np.asarray(im.resize((64, 64)), np.float32).reshape(-1) / 255.0

    out = []
    for p, pc, text in prompts:
        for sd in seeds:
            b = gen(text, 0.0, sd)
            for w in (1.0, 2.0):
                d = float(np.linalg.norm(gen(text, w, sd) - b))
                out.append(dict(prompt_id=p, seed=sd, w=w, pix_l2_base=d))
                print(f"    {p} seed{sd} w={w}: pix_l2_base={d:.3f}", flush=True)
    del pipe
    torch.cuda.empty_cache()
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--concept", choices=list(CONCEPTS), required=True)
    ap.add_argument("--steps", type=int, default=1000)
    ap.add_argument("--rank", type=int, default=8)
    ap.add_argument("--lr", type=float, default=2e-4)
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--out", type=str, default="")
    a = ap.parse_args()

    name = f"lora_{a.concept}"
    out = a.out or os.path.join(LORA_OUT, f"{name}.safetensors")
    steps = 4 if a.smoke else a.steps
    print(f"=== Y1: training {name} (concept {a.concept}) ===", flush=True)

    items = build_concept(a.concept)
    if a.smoke:
        items = items[:4]
    lat, emb = precompute(items)
    print(f"  latents {tuple(lat.shape)}  embeds {tuple(emb.shape)}", flush=True)
    final = train(lat, emb, steps, a.rank, a.lr, out)

    from longrun_p2 import PROMPTS
    print("  verification (w=0 vs w=1/2 on the evaluation prompts):", flush=True)
    rows = verify(out, PROMPTS[:2])

    import pandas as pd
    rec = dict(concept=a.concept, name=name, steps=steps, rank=a.rank,
               lr=a.lr, n_images=len(items), final_loss=final,
               path=out, bytes=os.path.getsize(out),
               max_pix_base=max(r["pix_l2_base"] for r in rows),
               min_pix_base=min(r["pix_l2_base"] for r in rows))
    os.makedirs(os.path.join(HERE, "out_y"), exist_ok=True)
    fp = os.path.join(HERE, "out_y", "y1_train_log.csv")
    pd.DataFrame([rec]).to_csv(fp, mode="a",
                               header=not os.path.exists(fp), index=False)
    pd.DataFrame(rows).to_csv(os.path.join(HERE, "out_y",
                                           f"y1_verify_{a.concept}.csv"),
                              index=False)
    print(f"  max pix_l2_base at w in {{1,2}} = {rec['max_pix_base']:.3f}", flush=True)
    if rec["max_pix_base"] < 2.0:
        print("  !! INERT: the LoRA barely moves the image.  Report this run as "
              "'not trained', never as 'no collinearity'.", flush=True)
    print(f"=== done {name} ===", flush=True)


if __name__ == "__main__":
    main()
